/// تنسيق المبالغ بشكل آمن مع اتجاه النص (bidi).
///
/// ## المشكلة اللي بيحلّها
/// الباك بيرجّع `formatted` بمسافات عادية: `"1 200 000 دج"`. جوه فقرة عربية
/// (RTL) خوارزمية الـ bidi بتعامل المسافة بين رقمين كمحرف محايد وبتاخدها
/// لاتجاه الفقرة، فمجموعات الأرقام بتتقلب وبتتعرض `"000 200 1"`. بيبان أكتر
/// كل ما الرقم يكبر — رقم من مجموعتين بيبان غريب، ومن تلاتة (مليون فأكتر)
/// بيبقى مقلوب بالكامل.
///
/// ## الحل
/// نستخدم `U+202F NARROW NO-BREAK SPACE` كفاصل آلاف. تصنيفه في الـ bidi هو
/// `CS` (Common Separator)، والقاعدة W4 بتقول إن فاصل مشترك واحد بين رقمين
/// بيتحوّل لنفس نوع الرقم — فالرقم كله بيبقى وحدة واحدة متتقلبش، وكمان
/// مابينكسرش على سطرين. وشكله أضيق شوية من المسافة العادية، وده المطلوب
/// في التصميم أصلًا.
library;

/// فاصل الآلاف — مسافة ضيّقة غير قابلة للكسر (U+202F).
const String kThinNbsp = '\u202F';

/// يرجّع الرقم بفواصل آلاف آمنة مع الاتجاه: `1200000` → `"1 200 000"`.
String formatAmount(int amount) {
  final negative = amount < 0;
  final digits = amount.abs().toString();
  final buf = StringBuffer();
  for (var i = 0; i < digits.length; i++) {
    if (i > 0 && (digits.length - i) % 3 == 0) buf.write(kThinNbsp);
    buf.write(digits[i]);
  }
  return negative ? '-${buf.toString()}' : buf.toString();
}

/// الرقم + العملة: `"1 200 000 دج"`.
///
/// المسافة قبل العملة عادية عن قصد — العملة نص عربي (RTL) والمفروض تقعد على
/// شمال الرقم في التخطيط العربي، والمسافة المحايدة هي اللي بتسمح بده.
String formatMoney(int amount, String currency) =>
    '${formatAmount(amount)} $currency';

/// يصلّح نص جاهز جاي من الـ API.
///
/// بيستبدل أي مسافة **بين رقمين** بالفاصل الآمن، ويسيب باقي المسافات (زي
/// اللي قبل «دج») زي ما هي. بنطبّقه عند حدود البيانات في
/// `MoneyModel.toEntity()` فكل `formatted` في التطبيق بيبقى مظبوط من غير ما
/// كل شاشة تعمل حاجة.
String bidiSafeNumber(String formatted) =>
    formatted.replaceAll(_gapBetweenDigits, kThinNbsp);

/// أي مسافة (عادية / غير قابلة للكسر / رفيعة) واقعة بين رقمين.
final RegExp _gapBetweenDigits = RegExp('(?<=\\d)[\u0020\u00A0\u2009](?=\\d)');
